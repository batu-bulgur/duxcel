#!/usr/bin/env python3
"""Derive exact test-only corner pixels from existing hash-pinned PNG pairs.

No browser, source rendering, dependencies, model-derived colors or tolerance.
The body header remains byte-for-byte unchanged. Every recorded white backdrop
pixel in the declared corner/seam rectangles is included, without inspecting its
foreground. Outside rows retain every foreground/background pair separately.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
RUN = '20261018T030846-reference-rail-1269'
REFERENCE = '1c8f3a6ff4dc532598a580abe44f369848cd00107a2a93a69e9289071440f876'
MANIFEST = '3a530675ab5935de2d932092eb9e22b648403a3e3862d9dbc9b9b89ac634dc4f'
BODY = '118c8d1f68570fc5477a6ad6b657857fe5b5ffb0073337c88c5020b1af5a9f9b'
WHITE = (255, 255, 255, 255)
PAIRS = {
    'narrow-100': ('ce83224134f4b537515ae1ee145486874d5e7b16da492d147ecde010164e145c',
                   '4858656ed00a0e07f82fab4ffc41bfb5de60e7608ae7110149331b8bc5f81b61'),
    'narrow-150': ('5019736b68c2e82077b391f27a450a968dba5ad079ac43d93b627aa47766f3ad',
                   '058362cd1f422946efe5f46db70a8ef041762333a0b319e3636c7ce978a897d3'),
}

def checked(path, expected):
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != expected:
        raise ValueError('Pinned input hash mismatch: ' + str(path))
    return data


def decode_png(data):
    if not data.startswith(b'\x89PNG\r\n\x1a\n'):
        raise ValueError('Not a PNG')
    at, packed = 8, bytearray()
    width = height = channels = 0
    while at < len(data):
        length, = struct.unpack_from('>I', data, at)
        kind, payload = data[at+4:at+8], data[at+8:at+8+length]
        crc, = struct.unpack_from('>I', data, at+8+length)
        if zlib.crc32(kind + payload) != crc:
            raise ValueError('PNG CRC mismatch')
        at += length + 12
        if kind == b'IHDR':
            width, height, depth, color, compression, filtering, interlace = struct.unpack('>IIBBBBB', payload)
            if not (0 < width <= 4096 and 0 < height <= 4096 and depth == 8 and color in (2, 6)
                    and compression == filtering == interlace == 0):
                raise ValueError('Only bounded noninterlaced RGB/RGBA8 is supported')
            channels = 3 if color == 2 else 4
        elif kind == b'IDAT':
            packed.extend(payload)
        elif kind == b'IEND':
            break
    stride = width * channels
    raw = zlib.decompress(packed)
    if not channels or len(raw) != height * (stride + 1):
        raise ValueError('Unexpected decoded PNG size')
    rows, previous = [], bytearray(stride)
    def paeth(a, b, c):
        p = a + b - c
        da, db, dc = abs(p-a), abs(p-b), abs(p-c)
        return a if da <= db and da <= dc else b if db <= dc else c
    for y in range(height):
        at = y * (stride + 1)
        mode, row = raw[at], bytearray(raw[at+1:at+1+stride])
        if mode > 4:
            raise ValueError('Invalid PNG row filter')
        for x in range(stride):
            left, above, diagonal = (row[x-channels] if x >= channels else 0), previous[x], (previous[x-channels] if x >= channels else 0)
            add = (0 if mode == 0 else left if mode == 1 else above if mode == 2
                   else (left+above)//2 if mode == 3 else paeth(left, above, diagonal))
            row[x] = (row[x] + add) & 255
        rows.append(row)
        previous = row
    def pixel(x, y):
        if not (0 <= x < width and 0 <= y < height):
            raise ValueError('Reference sample outside PNG')
        return tuple(rows[y][x*channels:(x+1)*channels]) + (() if channels == 4 else (255,))
    return width, height, pixel


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference-directory', type=Path, default=ROOT/'tests/results/runs'/RUN)
    parser.add_argument('--check', action='store_true', help='verify generated files without writing')
    args = parser.parse_args()
    directory = args.reference_directory
    reference = json.loads(checked(directory/'reference.json', REFERENCE))
    manifest = json.loads(checked(directory/'manifest.json', MANIFEST))
    checked(ROOT/'tests/shadow_reference.h', BODY)
    lines = ['/* Generated by tools/extract_shadow_corners.py; do not hand-edit.',
             '   Existing frozen run: ' + RUN,
             '   reference.json SHA256 ' + REFERENCE,
             '   manifest.json SHA256 ' + MANIFEST,
             '   White corner/seam selection depends only on recorded background, never foreground.',
             '   Outside rows retain all actual pairs; no production/scissor parity is inferred. */',
             '#ifndef DUXCEL_TEST_SHADOW_CORNER_REFERENCE_H', '#define DUXCEL_TEST_SHADOW_CORNER_REFERENCE_H',
             'typedef struct { unsigned short x,y; unsigned char foreground[4]; } ShadowCornerPixel;',
             'typedef struct { unsigned short x,y; unsigned char foreground[4],background[4]; } ShadowOutsidePixel;']
    metadata = {'run':RUN, 'reference_sha256':REFERENCE, 'manifest_sha256':MANIFEST,
                'body_header_sha256':BODY, 'inputs':manifest['inputs'], 'cases':[],
                'selection':'Every white-background pixel in declared corner/seam rectangles, including unchanged foreground; all pixels in immediately outside rows. No foreground-dependent sampling, tolerance or regenerated rendering.',
                'scope':'Pure reference fixture; no App/GPU, runtime animation, SQL or physical-input acceptance.'}
    for name, hashes in PAIRS.items():
        expanded = next(s for s in reference['states'] if s['case'] == name and s['name'] == 'expanded')
        dismissed = next(s for s in reference['states'] if s['case'] == name and s['name'] == 'dismissed')
        if expanded['capture']['file'] != name+'-expanded.png' or dismissed['capture']['file'] != name+'-dismissed.png':
            raise ValueError('Unexpected pinned capture name')
        w, h, foreground = decode_png(checked(directory/expanded['capture']['file'], hashes[0]))
        bw, bh, background = decode_png(checked(directory/dismissed['capture']['file'], hashes[1]))
        scale = expanded['state']['scale']; wrapper = expanded['state']['wrapper']['rect']
        assert (w,h) == (bw,bh) == (expanded['state']['viewport']['width']*2,expanded['state']['viewport']['height']*2)
        x0, right, top, bottom = [round(v*2) for v in (wrapper['x']-26*scale,wrapper['x'],wrapper['y'],wrapper['y']+wrapper['height'])]
        corner = math.ceil(21*scale*2)
        case = {'name':name,'scale':scale,'wrapper':wrapper,'foreground':expanded['capture'],'background':dismissed['capture'],'regions':[]}
        for kind, y0, rows in [('top',top,corner),('bottom',bottom-corner,corner),
                               ('top_seam',top+corner-1,2),('bottom_seam',bottom-corner-1,2),
                               ('outside_top',top-1,1),('outside_bottom',bottom,1)]:
            outside = kind.startswith('outside'); entries = []
            for y in range(y0,y0+rows):
                for x in range(x0,right):
                    bg, fg = background(x,y), foreground(x,y)
                    if outside or bg == WHITE:
                        if outside and fg != bg:
                            raise ValueError('Recorded outside row changed at '+str((name,kind,x,y)))
                        entries.append((x,y,fg,bg))
            region = {'kind':kind,'rect_device':[x0,y0,right-x0,rows], 'samples':len(entries),
                      'excluded_nonwhite':0 if outside else (right-x0)*rows-len(entries)}
            case['regions'].append(region)
            ident = name.replace('-','_')+'_'+kind
            lines.extend(['/* '+name+' '+kind+'; device rectangle '+str(region['rect_device'])+
                          '; samples '+str(len(entries))+'; excluded nonwhite '+str(region['excluded_nonwhite'])+'.',
                          '   expanded '+hashes[0]+'; dismissed '+hashes[1]+' */',
                          'static const '+('ShadowOutsidePixel' if outside else 'ShadowCornerPixel')+' '+ident+'[] = {'])
            for x,y,fg,bg in entries:
                rgba = '{'+','.join(map(str,fg))+'}'
                if outside: rgba += ',{'+','.join(map(str,bg))+'}'
                lines.append('    {'+str(x)+','+str(y)+','+rgba+'},')
            lines.append('};')
        metadata['cases'].append(case)
    lines.append('#endif')
    outputs = {ROOT/'tests/shadow_corner_reference.h':'\n'.join(lines)+'\n',
               ROOT/'tests/shadow_corner_reference.json':json.dumps(metadata,indent=2)+'\n'}
    for path, value in outputs.items():
        if args.check:
            if path.read_text() != value:
                raise ValueError('Generated fixture differs: '+str(path))
        else:
            path.write_text(value)
        print(path.relative_to(ROOT), hashlib.sha256(value.encode()).hexdigest())

if __name__ == '__main__':
    main()
